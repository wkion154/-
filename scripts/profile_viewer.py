"""Compare the previous PIL copy path with native Qt decode in isolated processes.
Fixtures are generated by this script; elapsed decode time excludes fixture creation.
RSS includes Python/Qt/PIL startup and all native allocations, not just image cache.
"""
import argparse
import json
import os
from pathlib import Path
import resource
import statistics
import subprocess
import sys
import tempfile
import time
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
os.environ.setdefault('QT_QPA_PLATFORM','offscreen')


def legacy(path,edge):
    from PIL import Image,ImageOps
    from PySide6.QtGui import QImage
    with Image.open(path) as image:
        image.draft('RGB',(edge,edge))
        image=ImageOps.exif_transpose(image)
        image.thumbnail((edge,edge),Image.Resampling.LANCZOS)
        image=image.convert('RGBA')
        data=image.tobytes('raw','RGBA')
        return QImage(data,image.width,image.height,image.width*4,QImage.Format.Format_RGBA8888).copy()


def measure(path,method,edge):
    # Import both implementations before timing for a fair process baseline.
    from app.images import decode_preview
    from PIL import Image
    samples=[]
    for _ in range(3):
        start=time.perf_counter()
        image=(legacy if method=='legacy' else decode_preview)(path,edge)
        samples.append((time.perf_counter()-start)*1000)
        dimensions=[image.width(),image.height()]
        del image
    return dict(method=method,edge=edge,dimensions=dimensions,median_ms=round(statistics.median(samples),2),
                samples_ms=[round(x,2) for x in samples],peak_process_rss_mib=round(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss/1024,2))


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--worker',action='store_true')
    parser.add_argument('--path')
    parser.add_argument('--method')
    parser.add_argument('--edge',type=int)
    args=parser.parse_args()
    if args.worker:
        print(json.dumps(measure(args.path,args.method,args.edge)))
        return
    from PIL import Image,ImageDraw
    result={'scope':'Linux isolated decoder processes, synthetic 7680x4320 JPEG and PNG. Three decodes per case. Native RSS includes runtime; no Windows or display-FPS claims.','cases':[]}
    with tempfile.TemporaryDirectory() as folder:
        # Generate outside the measured processes to avoid polluting RSS.
        for suffix in ('jpg','png'):
            path=Path(folder)/f'8k.{suffix}'
            image=Image.new('RGB',(7680,4320),'#75859b')
            draw=ImageDraw.Draw(image)
            for x in range(0,7680,120):
                draw.rectangle((x,0,x+59,4319),fill=(x%255,110,(x//20)%255))
            image.save(path)
            del draw,image
            for edge in (4096,7680):
                for method in ('legacy','native'):
                    run=subprocess.run([sys.executable,__file__,'--worker','--path',str(path),'--method',method,'--edge',str(edge)],capture_output=True,text=True,check=True)
                    result['cases'].append({'format':suffix,**json.loads(run.stdout)})
    print(json.dumps(result,indent=2))

if __name__=='__main__':main()
