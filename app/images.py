import hashlib
import json
import os
from pathlib import Path
import shutil
import time
import uuid
from PIL import Image, ImageOps
from PySide6.QtGui import QImage, QImageReader
from PySide6.QtCore import QSize, Qt

EXTENSIONS = {'.jpg', '.jpeg', '.png', '.webp', '.bmp', '.tif', '.tiff'}
MAX_PIXELS = 100_000_000
Image.MAX_IMAGE_PIXELS = MAX_PIXELS

def file_hash(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as f:
        for chunk in iter(lambda: f.read(1024*1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def inspect_image(path):
    path = Path(path).resolve(strict=True)
    if path.suffix.lower() not in EXTENSIONS:
        raise ValueError('지원하지 않는 파일 형식입니다.')
    with Image.open(path) as image:
        if image.width * image.height > MAX_PIXELS:
            raise ValueError('안전한 디코딩 한도(1억 픽셀)를 초과합니다.')
        fmt = image.format or path.suffix[1:].upper()
        image.verify()
    with Image.open(path) as image:
        image = ImageOps.exif_transpose(image)
        image.load()
        width, height = image.size
    return dict(path=str(path), name=path.name, sha256=file_hash(path), width=width, height=height,
                size=path.stat().st_size, format=fmt, registered=time.time(), managed=0)


def make_thumbnail(path, cache, key, edge=512):
    cache = Path(cache)
    cache.mkdir(parents=True, exist_ok=True)
    target = cache / (key + '-v1.jpg')
    stamp = target.with_suffix('.json')
    stat = Path(path).stat()
    signature = [str(Path(path).resolve()), stat.st_size, stat.st_mtime_ns]
    if target.exists():
        try:
            if json.loads(stamp.read_text()) != signature:
                raise OSError('Source changed')
            with Image.open(target) as image:
                image.load()
            return str(target)
        except (OSError, ValueError):
            target.unlink(missing_ok=True)
    temp = cache / (key + '-' + uuid.uuid4().hex + '.tmp')
    try:
        with Image.open(path) as image:
            image.draft('RGB', (edge, edge))
            image = ImageOps.exif_transpose(image)
            image.thumbnail((edge, edge), Image.Resampling.LANCZOS)
            if image.mode in ('RGBA', 'LA'):
                background = Image.new('RGB', image.size, '#202126')
                background.paste(image, mask=image.getchannel('A'))
                image = background
            else:
                image = image.convert('RGB')
            image.save(temp, format='JPEG', quality=88)
        temp.replace(target)
        stamp_temp = stamp.with_name(stamp.name+'.'+uuid.uuid4().hex+'.tmp')
        stamp_temp.write_text(json.dumps(signature))
        stamp_temp.replace(stamp)
    finally:
        temp.unlink(missing_ok=True)
    return str(target)


def import_paths(db, paths, cache, storage, managed, person, group, cancelled, progress=None):
    report = dict(added=0, duplicates=0, failed=[], cancelled=False)
    def candidates():
        for name in paths:
            path = Path(name)
            if path.is_dir():
                def onerror(error):
                    report['failed'].append((str(error.filename), str(error)))
                for root, dirs, files in os.walk(path, followlinks=False, onerror=onerror):
                    dirs[:] = [d for d in dirs if not (Path(root)/d).is_symlink()]
                    for file in files:
                        p = Path(root)/file
                        if p.suffix.lower() in EXTENSIONS:
                            yield p
            else:
                yield path
    last_progress = 0.0
    for i, path in enumerate(candidates()):
        if cancelled.is_set():
            report['cancelled'] = True
            break
        try:
            meta = inspect_image(path)
            if managed:
                folder = Path(storage)
                folder.mkdir(parents=True, exist_ok=True)
                dest = folder / (meta['sha256'] + path.suffix.lower())
                if dest.exists():
                    if file_hash(dest) != meta['sha256']:
                        raise ValueError('관리 저장소의 파일 무결성 오류')
                else:
                    temp = dest.with_name(dest.name+'.'+uuid.uuid4().hex+'.part')
                    try:
                        shutil.copyfile(path, temp)
                        if file_hash(temp) != meta['sha256']:
                            raise ValueError('복사 중 원본이 변경되었습니다.')
                        temp.replace(dest)
                    finally:
                        temp.unlink(missing_ok=True)
                meta.update(path=str(dest), managed=1)
            _, duplicate = db.register(meta, person, group)
            report['duplicates' if duplicate else 'added'] += 1
            # Visible thumbnails are generated by the view queue; no eager decoding of all files.
        except Exception as error:
            import logging
            logging.exception('Import failed: %s', path)
            report['failed'].append((str(path), str(error)))
        if progress and time.monotonic()-last_progress >= .1:
            progress(i+1)
            last_progress = time.monotonic()
    return report


# 100 MP RGBA is about 382 MiB. This is a decoder allocation guard, not a promise
# that the complete viewer process fits in 512 MiB (scene pixmaps use memory too).
QImageReader.setAllocationLimit(512)


def decode_preview(path, edge=4096, pixel_limit=MAX_PIXELS):
    """Decode directly to an owned QImage, allowing native JPEG downsampling.

    Avoids PIL -> RGBA -> bytes -> QImage copies for the interactive viewer.
    Other formats may still need their full source buffer inside Qt's decoder.
    """
    reader = QImageReader(str(path))
    reader.setAutoTransform(True)
    size = reader.size()
    if not size.isValid() or size.width()*size.height()>pixel_limit:
        raise ValueError(f'이미지 형식 또는 크기를 확인하세요. 최대 {pixel_limit:,}픽셀입니다.')
    if max(size.width(),size.height())>edge:
        reader.setScaledSize(size.scaled(QSize(edge,edge),Qt.AspectRatioMode.KeepAspectRatio))
    image = reader.read()
    if image.isNull():
        raise ValueError(reader.errorString())
    return image
